  test('REG-544 a class is renamed on the server; a duplicate name and a class gone from the server are refused with a reason', { tag: '@P2' }, async ({ signedIn: app, page, sharing }) => {
    const list = sharing.seedList(TEACHER, 'Physics 11', [STUDENT.sub])
    sharing.seedList(TEACHER, 'Chemistry', [])
    const screen = new SharingScreen(page)
    await screen.open()
    await screen.tab('Classes & people').click()
    await screen.classCard('Physics 11').getByRole('button', { name: 'Manage' }).click()
    const manage = screen.managePanel('Physics 11')
    const name = manage.getByRole('textbox', { name: 'Class name' })

    await screen.menu(manage, 'Rename')
    await name.fill('Chemistry')
    await manage.getByRole('button', { name: 'Save' }).click()
    await app.toasts.expectShown('You already have a class with that name')
    await name.press('Escape')
    await expect(name).toBeHidden()

    await screen.menu(manage, 'Rename')
    await name.fill('Physics 12')
    await name.press('Enter')
    await app.toasts.expectShown('Renamed to “Physics 12”')
    expect(sharing.callsTo('PATCH', `/api/sharing/lists/${list.id}`).map((c) => c.json)).toEqual([{ name: 'Physics 12' }])
    await expect(screen.managePanel('Physics 12').getByRole('heading', { name: 'Physics 12' })).toBeVisible()
    await expect(screen.classCard('Physics 12')).toBeVisible()

    sharing.override('PATCH', new RegExp(`^/api/sharing/lists/${list.id}$`), { status: 404, json: {} }, 1)
    const renamed = screen.managePanel('Physics 12')
    await screen.menu(renamed, 'Rename')
    await renamed.getByRole('textbox', { name: 'Class name' }).fill('Physics 13')
    await renamed.getByRole('button', { name: 'Save' }).click()
    await app.toasts.expectShown('That list no longer exists, or it isn\'t yours to rename.')
    expect(list.name).toBe('Physics 12')
  })

  test('REG-545 people are added to a class from the team and removed after a confirmation', { tag: '@P1' }, async ({ signedIn: app, page, sharing }) => {
    sharing.addOrgMember(TEACHER_ORG, STUDENT.sub)
    const list = sharing.seedList(TEACHER, 'Physics 11', [])
    const screen = new SharingScreen(page)
    await screen.open()
    await screen.tab('Classes & people').click()
    await screen.classCard('Physics 11').getByRole('button', { name: 'Manage' }).click()
    const manage = screen.managePanel('Physics 11')
    await expect(manage).toContainText('Nobody yet — add people to share with them all at once.')
    await manage.getByRole('button', { name: 'Add people' }).click()
    const add = new AddPeopleDialog(page, 'Add people to “Physics 11”')
    await expect(add.tab(/^Your team \(1\)$/)).toBeVisible()
    await expect(add.tab(/^Recently searched$/)).toBeVisible()
    await add.person('Sam Student').click()
    await app.toasts.expectShown('Sam Student added to Physics 11')
    await expect(add.dialog).toBeHidden()
    expect(sharing.callsTo('POST', `/api/sharing/lists/${list.id}/members`).map((c) => c.json)).toEqual([{ userId: STUDENT.sub }])
    expect(list.memberIds).toEqual([STUDENT.sub])
    await expect(manage).toContainText('People · 1')

    // Adding them again is refused before any request.
    await manage.getByRole('button', { name: 'Add people' }).click()
    await expect(add.person('Sam Student')).toBeDisabled()
    await expect(add.person('Sam Student')).toContainText('Added')
    await add.dialog.getByRole('button', { name: 'Close' }).click()

    let message = ''
    page.once('dialog', (d) => { message = d.message(); void d.accept() })
    await manage.getByRole('button', { name: 'Remove Sam Student' }).click()
    await expect.poll(() => message).toBe('Remove Sam Student from “Physics 11”?\n\nThey stop receiving this class\'s live updates. Anything already shared with them stays with them.')
    await app.toasts.expectShown('Sam Student removed')
    expect(sharing.callsTo('DELETE', `/api/sharing/lists/${list.id}/members/${STUDENT.sub}`)).toHaveLength(1)
    expect(list.memberIds).toEqual([])
    await expect(manage).toContainText('Nobody yet — add people to share with them all at once.')
  })

