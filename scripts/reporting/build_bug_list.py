"""Writes docs/10-BUGS-TO-RAISE.md: every defect as a short, testable bug report for testers.

  python scripts/reporting/build_bug_list.py --results reports/run-12/results.json [--results ...]

Same source as docs/08 (defects_old.json + defects_register.NEW), in plain steps a tester can follow
by hand, plus what the latest automated runs showed for each one. Results files are optional; each
known-defect test's outcome is read from them (a later file wins for the same test).
"""
import argparse, json, re, sys
from collections import OrderedDict
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
from defects_register import NEW  # noqa: E402

OLD = json.load(open(HERE / 'defects_old.json', encoding='utf-8'))
DEFECTS = OrderedDict((d['id'], d) for d in OLD + NEW)
ID_RE = re.compile(r'\b((?:SMK|SAN|REG|PST|OFF|A11Y|PRF|API)-\d{3})\b')
PRI_ORDER = {'P1': 0, 'P2': 1, 'P3': 2}

ap = argparse.ArgumentParser()
ap.add_argument('--results', action='append', default=[])
args = ap.parse_args()

# What the latest runs showed, per defect: from the known-defect annotation on each test.
seen = {}      # DEF id -> list of (test id, project, outcome, run date)
latest_run = {}  # (test, project) -> its failure at the latest run that ran it, or None: a later run supersedes
for f in args.results:
    run = json.load(open(f, encoding='utf-8'))
    when = (run.get('stats', {}).get('startTime') or '')[:10]
    def visit(s):
        for sp in s.get('specs', []):
            tid = (ID_RE.search(sp['title']) or [None])[0] if ID_RE.search(sp['title']) else None
            for t in sp['tests']:
                defs = [a.get('description', '')[:7] for a in t.get('annotations', []) if a.get('type') == 'known-defect']
                last = (t.get('results') or [{}])[-1]
                for d in defs:
                    outcome = 'reproduced' if t['status'] == 'expected' else 'TEST PASSED: may be fixed' if t['status'] == 'unexpected' else t['status']
                    seen.setdefault(d, {})[(tid, t['projectName'])] = (outcome, when)
                for a in t.get('annotations', []):
                    m = re.match(r'(DEF-\d+) seen', a.get('type', ''))
                    if m:
                        seen.setdefault(m.group(1), {})[(tid, t['projectName'])] = ('seen (recorded, not failed)', when)
                if t['status'] == 'unexpected' and not defs:
                    err = re.sub(r'\x1b\[[0-9;]*m', '', ((last.get('errors') or [{}])[0].get('message') or ''))
                    latest_run[(tid or sp['title'], t['projectName'])] = (tid, t['projectName'], sp['title'], sp['file'], sp['line'], err.strip().split('\n')[0][:200], when)
                elif t['status'] in ('expected', 'flaky'):
                    latest_run[(tid or sp['title'], t['projectName'])] = None
        for x in s.get('suites', []):
            visit(x)
    for s in run.get('suites', []):
        visit(s)


def needs(d):
    """What a tester needs to try it, in plain words."""
    mod, tests = d['module'], d.get('tests', '')
    ids = [int(m) for m in re.findall(r'REG-(\d{3})', tests)]
    out = []
    if any(910 <= i <= 949 for i in ids) or mod == 'Live share':
        out.append('two real accounts: a teacher on a paid plan and a student on Free, in two browsers')
    elif mod in ('Sharing',) and not any(910 <= i <= 949 for i in ids):
        out.append('a paid-plan account (sharing needs a subscription) and a second account to receive')
    if mod == 'Cloud backup' or any(900 <= i <= 907 for i in ids) or i_in(ids, 940):
        out.append('an account signed in to MuulOrigin (Pro for cloud backup)')
    if mod == 'Phone':
        out.append('a phone, or Chrome with a phone-sized window (device toolbar)')
    if mod == 'Touch devices':
        out.append('a touch screen or tablet (a stylus where the steps say pen)')
    if mod in ('Offline',):
        out.append('a way to turn the internet off (airplane mode, or DevTools > Network > Offline)')
    if mod == 'Accessibility':
        out.append('the keyboard only (Tab, Enter, Escape) or a screen reader, as the steps say')
    return out or ['Chrome on a computer; any account, or none']


def i_in(ids, n):
    return n in ids


defects = sorted(DEFECTS.values(), key=lambda d: (PRI_ORDER[d['pri']], d['module'], d['id']))
L = [
    '# Bugs to raise',
    '',
    f'> Generated by `scripts/reporting/build_bug_list.py` on {date.today().isoformat()} from the defect register (the same source as `08-DEFECTS-AND-LIMITATIONS.md`). Edit the register, not this file.',
    '',
    'Every bug below was found by the automated tests. Each one is written so a tester can check it by hand in a few minutes and raise it on GitHub:',
    '',
    '1. Read **You need**, and set that up.',
    '2. Follow the **Steps**, in order.',
    '3. Compare what you see with **Expected** and **Actual**.',
    '4. If you see the **Actual** behaviour, raise it with the **GitHub issue title** given, and paste the steps, expected and actual into the issue.',
    '',
    '**Where to test:** the live app (https://cognitivecanvas.muulorigin.com) in Chrome on a computer, unless a bug says phone, tablet or iPad. '
    'Start from a fresh browser profile (or an Incognito window) when a bug says "a fresh profile". '
    'Never use a real person\'s account for bugs that delete, restore or share data: use a test account.',
    '',
    '**Latest automated result** says what the newest test run showed: *reproduced* means the test that checks this bug failed exactly as the bug describes on that date. '
    '*TEST PASSED: may be fixed* means the bug did not show; check by hand before raising it.',
    '',
    '## Summary',
    '',
    f'{len(defects)} bugs: ' + ', '.join(f"{sum(1 for d in defects if d['pri'] == p)} {p}" for p in ('P1', 'P2', 'P3')) + ' (P1 = fix first).',
    '',
    '| Bug | Priority | Area | What is wrong | Latest automated result |',
    '|---|---|---|---|---|',
]


def latest(d):
    if d.get('kind') == 'intermittent':
        return 'intermittent: seen now and then, not on every run'
    s = seen.get(d['id'])
    if not s:
        return 'not in the runs given'
    outs = sorted({f'{o} ({w})' for (o, w) in s.values()})
    return '; '.join(outs)


for d in defects:
    L.append(f"| [{d['id']}](#{d['id'].lower()}) | {d['pri']} | {d['module']} | {d['title']} | {latest(d)} |")
L += ['']

for p in ('P1', 'P2', 'P3'):
    group = [d for d in defects if d['pri'] == p]
    if not group:
        continue
    L += [f'## {p} bugs', '']
    for d in group:
        L += [f"### {d['id']}", '', f"**{d['title']}**", '']
        L.append(f"- **Priority:** {d['pri']} · **Area:** {d['module']} · **Checked by test:** {d.get('tests', '-')}")
        L.append(f"- **Latest automated result:** {latest(d)}")
        L.append('- **You need:** ' + '; '.join(needs(d)))
        L.append(f"- **GitHub issue title:** `[{d['module']}] {d['title']}`")
        L += ['', '**Steps**', '']
        for i, step in enumerate(d.get('steps') or [], 1):
            L.append(f'{i}. {step}')
        for extra in d.get('extra') or []:
            L.append(f'   - {extra}')
        exp = d.get('expected', '').strip()
        act = d.get('actual', '').strip()
        L += ['', f"**Expected:** {exp[:1].upper() + exp[1:]}", '', f"**Actual:** {act[:1].upper() + act[1:]}", '']
        if d.get('dev'):
            L += [f"*For developers:* {d['dev']}", '']

unexpected = [v for v in latest_run.values() if v]  # still failing at their latest run, with no known defect behind them
if unexpected:
    L += ['## Failures in the latest runs that are not on the list above', '',
          'These tests failed without a known bug behind them. Each needs a look before it is raised: it may be a new bug, a slow or busy machine, or the test itself.', '',
          '| Test | Where it runs | What it checks | First error | Run |', '|---|---|---|---|---|']
    for tid, proj, title, file, line, err, when in unexpected:
        L.append(f"| {tid or '-'} | {proj} | {title.replace('|', '/')} (`tests/{file.replace(chr(92), '/')}:{line}`) | {err.replace('|', '/')} | {when} |")
    L.append('')

out = REPO / 'docs' / '10-BUGS-TO-RAISE.md'
out.write_text('\n'.join(L), encoding='utf-8', newline='\r\n')
print(f'written {out}: {len(defects)} bugs, {len(unexpected)} other failures')
