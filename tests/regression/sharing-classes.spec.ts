  test('REG-547 several classes are deleted at once in Select mode', { tag: '@P2' }, async ({ signedIn: app, page, sharing }) => {
    const a = sharing.seedList(TEACHER, 'Physics 11', [STUDENT.sub])
    const b = sharing.seedList(TEACHER, 'Chemistry', [STUDENT_2.sub])
    sharing.seedList(TEACHER, 'Biology', [])
    const screen = new SharingScreen(page)
    await screen.open()
    await screen.tab('Classes & people').click()
    const classes = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Classes · 3' }) })
    await classes.getByRole('button', { name: 'Select', exact: true }).click()
    await page.getByRole('checkbox').filter({ hasText: 'Physics 11' }).click()
    await page.getByRole('checkbox').filter({ hasText: 'Chemistry' }).click()
    await expect(page.getByText('2 selected')).toBeVisible()
    await page.getByRole('button', { name: 'Delete 2' }).click()
    const modal = page.getByRole('dialog', { name: 'Delete 2 classes?' })
    await expect(modal).toContainText('Physics 11, Chemistry')
    await modal.getByRole('button', { name: 'Delete', exact: true }).click()
    await app.toasts.expectShown('2 classes deleted')
    expect(sharing.callsTo('DELETE', /^\/api\/sharing\/lists\/[^/]+$/).map((c) => c.path).sort()).toEqual([`/api/sharing/lists/${a.id}`, `/api/sharing/lists/${b.id}`].sort())
    expect(sharing.listsOf(TEACHER).map((l) => l.name)).toEqual(['Biology'])
    await expect(page.getByRole('heading', { name: 'Classes · 1' })).toBeVisible()
  })

  test('REG-548 People lists the team and class members; a person can be shared with, or removed from every class and share', { tag: '@P1' }, async ({ signedIn: app, page, sharing }) => {
    sharing.addOrgMember(TEACHER_ORG, STUDENT.sub)
    const list = sharing.seedList(TEACHER, 'Physics 11', [STUDENT_2.sub])
    sharing.seedThread(TEACHER, STUDENT_2.sub)
    const screen = new SharingScreen(page)
    await screen.open()
    await screen.tab('Classes & people').click()
    await expect(screen.tab('Classes & people')).toHaveAccessibleName('Classes & people 3') // 1 class + 2 people
    await expect(page.getByRole('heading', { name: 'People · 2' })).toBeVisible()
    await expect(screen.personRow('Sam Student')).toContainText('sam.student@example.invalid · Team member · 0 shares')
    await expect(screen.personRow('Riya Reader')).toContainText('riya.reader@example.invalid · Physics 11 · 1 share')

    await screen.menu(screen.personRow('Sam Student'), 'Share with Sam Student', 'Actions for Sam Student')
    const c = new ShareComposerDialog(page)
    await expect(c.removeChip('Sam Student')).toBeVisible()
    await c.cancel.click()

    await screen.menu(screen.personRow('Riya Reader'), 'Remove from my classes and shares…', 'Actions for Riya Reader')
    const modal = page.getByRole('dialog', { name: 'Remove 1 person?' })
    await expect(modal).toContainText('Riya Reader')
    await expect(modal).toContainText('They are taken out of every class of yours, stop receiving your live shares, and the copies you sent them leave your history.')
    await modal.getByRole('button', { name: 'Remove', exact: true }).click()
    await app.toasts.expectShown('1 person removed — they keep what they received')
    expect(sharing.callsTo('DELETE', `/api/sharing/lists/${list.id}/members/${STUDENT_2.sub}`)).toHaveLength(1)
    expect(sharing.callsTo('DELETE', `/api/sharing/threads/${STUDENT_2.sub}`)).toHaveLength(1)
    expect(list.memberIds).toEqual([])
    await expect(screen.personRow('Riya Reader')).toHaveCount(0)
    // A team member with nothing shared offers no removal here (that is done on Team Members).
    await screen.personRow('Sam Student').getByRole('button', { name: 'Actions for Sam Student' }).click()
    await expect(page.getByRole('menu').getByRole('menuitem')).toHaveText(['Share with Sam Student'])
  })

